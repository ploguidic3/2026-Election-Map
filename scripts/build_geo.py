"""Build data/counties-geo.js: per-state SVG county paths for the map.

Source: us-atlas@3.0.1 counties-albers-10m.json (pre-projected Albers USA,
from the npm package tarball). Run: python scripts/build_geo.py <counties-albers-10m.json>
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "data" / "counties-geo.js"
WIDTH = 1000  # every state is scaled to this viewBox width


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring_points(ring, arcs):
    pts = []
    for i in ring:
        arc = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(arc if not pts else arc[1:])
    return pts


def main():
    topo = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    arcs = decode_arcs(topo)
    by_state = defaultdict(dict)
    for geom in topo["objects"]["counties"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
        rings = [ring_points(r, arcs) for poly in polys for r in poly]
        by_state[geom["id"][:2]][geom["id"]] = rings
    out = {}
    for st, counties in by_state.items():
        if st == "02":  # Alaska results are by house district, not borough.
            continue
        xs = [x for rings in counties.values() for r in rings for x, _ in r]
        ys = [y for rings in counties.values() for r in rings for _, y in r]
        x0, y0 = min(xs), min(ys)
        k = WIDTH / (max(xs) - x0)
        paths = {}
        for fips, rings in counties.items():
            d = []
            for r in rings:
                coords = []
                last = None
                for x, y in r:
                    p = (round((x - x0) * k, 1), round((y - y0) * k, 1))
                    if p != last:
                        coords.append(f"{p[0]:g},{p[1]:g}")
                        last = p
                d.append("M" + "L".join(coords) + "Z")
            paths[fips] = "".join(d)
        out[st] = {"w": WIDTH, "h": round((max(ys) - y0) * k, 1), "paths": paths}
    OUT.write_text(
        "// Generated by scripts/build_geo.py from us-atlas@3.0.1 (ISC). Keyed by state FIPS.\n"
        f"window.COUNTY_GEO = {json.dumps(out, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(out)} states, {OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
