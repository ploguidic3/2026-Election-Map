"""Build data/counties-geo.js and data/states-geo.js: SVG paths for the maps.

Source: us-atlas@3.0.1 counties-albers-10m.json and states-albers-10m.json
(pre-projected Albers USA, from the npm package tarball).
Run: python scripts/build_geo.py <us-atlas package directory>
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
OUT = DATA / "counties-geo.js"
STATES_OUT = DATA / "states-geo.js"
WIDTH = 1000  # every state is scaled to this viewBox width


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring_points(ring, arcs):
    pts = []
    for i in ring:
        arc = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(arc if not pts else arc[1:])
    return pts


def path_d(rings, fx):
    d = []
    for r in rings:
        coords = []
        last = None
        for pt in r:
            p = fx(pt)
            if p != last:
                coords.append(f"{p[0]:g},{p[1]:g}")
                last = p
        d.append("M" + "L".join(coords) + "Z")
    return "".join(d)


def ring_area_centroid(r):
    a = cx = cy = 0.0
    for (x0, y0), (x1, y1) in zip(r, r[1:] + r[:1]):
        f = x0 * y1 - x1 * y0
        a += f
        cx += (x0 + x1) * f
        cy += (y0 + y1) * f
    if not a:
        return 0.0, r[0]
    return abs(a / 2), (cx / (3 * a), cy / (3 * a))


def build_states(src):
    topo = json.loads((src / "states-albers-10m.json").read_text(encoding="utf-8"))
    arcs = decode_arcs(topo)
    out = {}
    for geom in topo["objects"]["states"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
        rings = [ring_points(r, arcs) for poly in polys for r in poly]
        outer = [ring_points(poly[0], arcs) for poly in polys]
        _, (lx, ly) = max((ring_area_centroid(r) for r in outer), key=lambda t: t[0])
        out[geom["id"]] = {
            "name": geom["properties"]["name"],
            "d": path_d(rings, lambda p: (round(p[0], 1), round(p[1], 1))),
            "label": [round(lx, 1), round(ly, 1)],
        }
    STATES_OUT.write_text(
        "// Generated by scripts/build_geo.py from us-atlas@3.0.1 (ISC). Keyed by state FIPS; viewBox 0 0 975 610.\n"
        f"window.STATE_GEO = {json.dumps(out, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"wrote {STATES_OUT} ({len(out)} states, {STATES_OUT.stat().st_size // 1024} KiB)")


def main():
    src = Path(sys.argv[1])
    build_states(src)
    topo = json.loads((src / "counties-albers-10m.json").read_text(encoding="utf-8"))
    arcs = decode_arcs(topo)
    by_state = defaultdict(dict)
    for geom in topo["objects"]["counties"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
        rings = [ring_points(r, arcs) for poly in polys for r in poly]
        by_state[geom["id"][:2]][geom["id"]] = rings
    out = {}
    for st, counties in by_state.items():
        if st == "02":  # Alaska results are by house district, not borough.
            continue
        xs = [x for rings in counties.values() for r in rings for x, _ in r]
        ys = [y for rings in counties.values() for r in rings for _, y in r]
        x0, y0 = min(xs), min(ys)
        k = WIDTH / (max(xs) - x0)
        fx = lambda p: (round((p[0] - x0) * k, 1), round((p[1] - y0) * k, 1))
        paths = {fips: path_d(rings, fx) for fips, rings in counties.items()}
        out[st] = {"w": WIDTH, "h": round((max(ys) - y0) * k, 1), "paths": paths}
    OUT.write_text(
        "// Generated by scripts/build_geo.py from us-atlas@3.0.1 (ISC). Keyed by state FIPS.\n"
        f"window.COUNTY_GEO = {json.dumps(out, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(out)} states, {OUT.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main()
