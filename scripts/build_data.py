"""Build data/pres2024.js from the 2024 county-level presidential results.

Source: tonmcg/US_County_Level_Election_Results_08-24 (county totals; Alaska by
state house district). Run: python scripts/build_data.py [path-or-url]
"""
import csv
import io
import json
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

SOURCE = (
    "https://raw.githubusercontent.com/tonmcg/US_County_Level_Election_Results_08-24/"
    "master/2024_US_County_Level_Presidential_Results.csv"
)
OUT = Path(__file__).resolve().parent.parent / "data" / "pres2024.js"


def read_source(arg):
    if arg and not arg.startswith("http"):
        return Path(arg).read_text(encoding="utf-8")
    with urllib.request.urlopen(arg or SOURCE) as resp:
        return resp.read().decode("utf-8")


def main():
    text = read_source(sys.argv[1] if len(sys.argv) > 1 else None)
    states = defaultdict(list)
    for row in csv.DictReader(io.StringIO(text)):
        states[row["state_name"]].append([
            row["county_fips"].zfill(5),
            row["county_name"],
            int(row["votes_dem"]),
            int(row["votes_gop"]),
            int(row["total_votes"]),
        ])
    for rows in states.values():
        rows.sort(key=lambda r: r[1])
    body = json.dumps(dict(sorted(states.items())), separators=(",", ":"))
    OUT.write_text(
        "// Generated by scripts/build_data.py. Rows: [fips, name, dem, gop, total].\n"
        f"window.PRES2024 = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({sum(len(r) for r in states.values())} rows, {len(states)} states)")


if __name__ == "__main__":
    main()
